// ----------------------------------------------------------------------
// Numeracion de los codigos de miembro.
//
// El codigo es `EDR-NNNNN` y no dice nada de donde esta la persona: ni pais ni
// provincia. Hasta agosto de 2026 los llevaba (`DO-SD-10001`) y se quitaron
// porque la provincia cambia cuando alguien se muda —el codigo decia una cosa y
// su destacamento otra— y porque cada provincia numeraba por separado, de modo
// que dos personas podian compartir numero y, como al entrar solo se teclea el
// numero, una de las dos se quedaba fuera.
// ----------------------------------------------------------------------

export const PRIMER_NUMERO_MIEMBRO = 10001;
