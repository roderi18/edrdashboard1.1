// a partir de la RUTA -division, carpetas y nombre-, nunca del nombre suelto:
// hay premios que se llaman igual en varias divisiones ("Lectura de la Biblia"
// esta en las tres) y un id por nombre los confundiria entre si.
//
// Dos cosas del inventario que aqui NO estan, a proposito:
//
//   - Los "(1)" de los nombres: son copias del mismo archivo, asi que Fotografia
//     y 1 SAMUEL aparecen una sola vez.
//   - Los dos "Orden.png" de los premios biblicos: son una hoja con el orden de
