// ----------------------------------------------------------------------
// Del arbol de arriba a los nodos planos que consume la aplicacion: cada uno con
// su id, su nombre y el padre del que cuelga.
// ----------------------------------------------------------------------

const nodoBase = (id, name, parentId, type) => ({
  id,
  name,
  type,
  parentId,
  size: 0,
  totalFiles: 0,
  shared: [],
  isFavorited: false,
  createdAt: new Date(),
  modifiedAt: null,
  tags: [],
});

export function construirNodosAscenso() {
  const nodos = [];

  DIVISIONES_ASCENSO.forEach(({ nombre, sigla }) => {
    const idDivision = idDeRutaAscenso(nombre);

    nodos.push({
      id: idDivision,
      name: nombre,
      type: 'folder',
      parentId: ID_RAIZ_SISTEMA_ASCENSO,
      target: sigla,
      total: 0,
      completed: 0,
      updatedAt: null,
      createdAt: new Date(),
      modifiedAt: null,
      tags: [],
    });

    (PREMIOS_EN_RAIZ_ASCENSO[nombre] || []).forEach((premio) => {
      nodos.push(nodoBase(idDeRutaAscenso(nombre, premio), premio, idDivision, 'pdf'));
    });

    const recorrer = (contenido, rutaPadre, idPadre) => {
      Object.entries(contenido).forEach(([clave, valor]) => {
        const ruta = [...rutaPadre, clave];
        const id = idDeRutaAscenso(nombre, ...ruta);

        nodos.push(nodoBase(id, clave, idPadre, 'folder'));

        if (Array.isArray(valor)) {
          valor.forEach((premio) => {
            nodos.push(nodoBase(idDeRutaAscenso(nombre, ...ruta, premio), premio, id, 'pdf'));
          });

          return;
        }

        recorrer(valor, ruta, id);
      });
    };

    recorrer(ARBOL_ASCENSO[nombre] || {}, [], idDivision);
  });

  return nodos;
}
