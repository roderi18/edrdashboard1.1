export const ID_RAIZ_SISTEMA_ASCENSO = 'sistema-de-ascenso';

// El id sale de la ruta entera, con doble guion bajo entre tramos para que no se
// confunda con los guiones que ya llevan los nombres ("Destreza - Plata").
export const idDeRutaAscenso = (...tramos) =>
  tramos
    .map((tramo) =>
      String(tramo)
        .toLowerCase()
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, '')
    )
    .join('__');

