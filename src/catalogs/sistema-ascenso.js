// Transcripcion del inventario "Exploradores, Seguidores y Pioneros" (490
// archivos, 28/08/2026): cada division con sus carpetas y, dentro, los premios
// que contiene. De aqui salen tres cosas a la vez, y por eso vive en un solo
// sitio:
